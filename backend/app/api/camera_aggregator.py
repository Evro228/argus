import time
from datetime import datetime
from typing import Any, Dict, List, Optional

# Track last sync state
_SYNC_STATE: Dict[str, Any] = {
    "status": "SYNCHRONIZED",
    "last_sync": datetime.utcnow().isoformat() + "Z",
    "sync_count": 1,
    "last_error": None,
}


def normalize_camera_feed(raw: Dict[str, Any], default_repo: str = "") -> Dict[str, Any]:
    """
    Normalizes diverse camera schemas from different GitHub formats (GeoJSON, M3U8, RTSP, MJPEG)
    into the standard ARGUS tactical camera schema.
    """
    cid = raw.get("id") or f"CAM_GH_{int(time.time() * 1000)}"
    city = raw.get("city") or raw.get("loc") or "Unknown Hub"
    country = (raw.get("country") or "INTL").upper()
    lat = float(raw.get("lat") or raw.get("latitude") or 0.0)
    lon = float(raw.get("lon") or raw.get("longitude") or 0.0)
    
    stream_type = raw.get("stream_type") or ("mjpeg" if "mjpeg" in raw.get("stream_url", "").lower() else "hls")
    
    return {
        "id": cid,
        "name": raw.get("name") or raw.get("title") or f"{city} Feed",
        "city": city,
        "city_en": raw.get("city_en") or city,
        "region": raw.get("region") or raw.get("county") or "Global Node",
        "district": raw.get("district") or "International Infrastructure",
        "country": country,
        "flag": raw.get("flag") or "🌐",
        "category": raw.get("category") or "GitHub Open Data / Infrastructure",
        "lat": lat,
        "lon": lon,
        "fov_deg": int(raw.get("fov_deg") or 110),
        "stream_type": stream_type,
        "protocol": raw.get("protocol") or stream_type.upper(),
        "stream_url": raw.get("stream_url") or "",
        "snapshot_url": raw.get("snapshot_url") or raw.get("img") or "",
        "resolution": raw.get("resolution") or "1080p FHD",
        "fps": int(raw.get("fps") or 25),
        "operator": raw.get("operator") or f"Public Feed (via {default_repo})",
        "source_repo": raw.get("source_repo") or default_repo,
        "source_repo_url": raw.get("source_repo_url") or (f"https://github.com/{default_repo}" if default_repo else ""),
        "source_format": raw.get("source_format") or "JSON",
        "status": raw.get("status") or "ONLINE",
    }


