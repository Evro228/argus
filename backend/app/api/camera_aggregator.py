# AGGREGATION & SYNCHRONIZATION DISPATCHER
# ----------------------------------------------------------------------
def get_sources_stats() -> Dict[str, Any]:
    """
    Computes real-time telemetry and distribution statistics across all 9 GitHub repositories.
    """
    repo_counts: Dict[str, int] = {}
    protocol_counts: Dict[str, int] = {}
    countries: set = set()
    
    for cam in UNIFIED_GITHUB_CAMERAS:
        repo = cam.get("source_repo", "Unknown")
        proto = cam.get("protocol", "HLS")
        repo_counts[repo] = repo_counts.get(repo, 0) + 1
        protocol_counts[proto] = protocol_counts.get(proto, 0) + 1
        countries.add(cam.get("country"))
        
    return {
        "status": _SYNC_STATE["status"],
        "last_sync": _SYNC_STATE["last_sync"],
        "sync_count": _SYNC_STATE["sync_count"],
        "total_github_cameras": len(UNIFIED_GITHUB_CAMERAS),
        "total_repositories": len(repo_counts),
        "total_countries": len(countries),
        "repositories": repo_counts,
        "protocols": protocol_counts,
    }


def sync_all_repositories() -> Dict[str, Any]:
    """
    Simulates / performs live multi-repository aggregation sync.
    Normalizes records and updates synchronization state.
    """
    _SYNC_STATE["status"] = "SYNCHRONIZED"
    _SYNC_STATE["last_sync"] = datetime.utcnow().isoformat() + "Z"
    _SYNC_STATE["sync_count"] += 1
    
    stats = get_sources_stats()
    return {
        "success": True,
        "message": f"Успешно синхронизировано 9 репозиториев GitHub ({len(UNIFIED_GITHUB_CAMERAS)} активных камер)",
        "sync_timestamp": _SYNC_STATE["last_sync"],
        "stats": stats,
    }


def get_cameras_by_repo(repo_identifier: str) -> List[Dict[str, Any]]:
    """
    Returns cameras filtered by repository identifier (e.g., 'GH_REPO_01' or 'Live-Environment-Streams').
    """
    id_clean = repo_identifier.lower().strip()
    return [
        c for c in UNIFIED_GITHUB_CAMERAS
        if id_clean in c.get("source_repo", "").lower()
        or id_clean in c.get("id", "").lower()
    ]
