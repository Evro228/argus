async def list_open_cameras(
    search: Optional[str] = Query(None, description="Текстовый поиск по городу, региону или названию"),
    country: Optional[str] = Query(None, description="Код страны (RU, US, TR, etc.)"),
    district: Optional[str] = Query(None, description="Федеральный округ РФ или мировой регион"),
    category: Optional[str] = Query(None, description="Категория (Metropolitan, Maritime, Aviation, etc.)"),
    limit: int = Query(200, ge=1, le=500),
):
    """
    Возвращает каталог открытых публичных камер видеонаблюдения с гибкой фильтрацией.
    Поддерживает поиск по всем городам РФ и мира.
    """
    air_gap = is_air_gap_enabled()
    results = ALL_CAMERAS

    if country:
        c_upper = country.upper()
        results = [c for c in results if c["country"] == c_upper]

    if district:
        d_lower = district.lower()
        results = [c for c in results if d_lower in c.get("district", "").lower()]

    if category:
        cat_lower = category.lower()
        results = [c for c in results if cat_lower in c.get("category", "").lower()]

    if search:
        s_lower = search.lower().strip()
        results = [
            c for c in results
            if s_lower in c["name"].lower()
            or s_lower in c["city"].lower()
            or s_lower in c.get("city_en", "").lower()
            or s_lower in c.get("region", "").lower()
            or s_lower in c.get("operator", "").lower()
        ]

    # In Air-Gapped Stealth Mode, we ensure no live remote stream leakage
    sanitized = []
    for c in results[:limit]:
        item = dict(c)
        if air_gap:
            item["status"] = "AIR_GAPPED_STEALTH"
            item["stream_url"] = "/api/cameras/offline_test_pattern"
            item["snapshot_url"] = "/api/cameras/offline_test_pattern"
        sanitized.append(item)

    return {
        "success": True,
        "air_gap_mode": air_gap,
        "timestamp": datetime.utcnow().isoformat() + "Z",
        "total_catalog": len(ALL_CAMERAS),
        "ru_catalog_count": len(RU_CAMERAS_CATALOG),
        "global_catalog_count": len(GLOBAL_CAMERAS_CATALOG),
        "matched_count": len(sanitized),
        "cameras": sanitized,
    }


@router.get("/cities")
async def list_cities():
    """
    Возвращает реестр всех доступных городов РФ и мира с количеством открытых камер.
    Позволяет быстро переключать города на Видеостене (CCTV Matrix).
    """
    cities = get_cities_summary()
    ru_cities = [c for c in cities if c["country"] == "RU"]
    global_cities = [c for c in cities if c["country"] != "RU"]

    return {
        "success": True,
        "total_cities": len(cities),
        "ru_cities_count": len(ru_cities),
        "global_cities_count": len(global_cities),
        "cities": cities,
    }


@router.get("/detail/{camera_id}")
async def get_camera_detail(camera_id: str):
    """
    Возвращает подробные технические параметры конкретной камеры и ссылку на прямой поток.
    """
    cam = next((c for c in ALL_CAMERAS if c["id"] == camera_id), None)
    if not cam:
        raise HTTPException(status_code=404, detail=f"Камера {camera_id} не найдена в каталоге")

    air_gap = is_air_gap_enabled()
    res = dict(cam)
    if air_gap:
        res["status"] = "AIR_GAPPED_STEALTH"
        res["stream_url"] = "/api/cameras/offline_test_pattern"

    return {
        "success": True,
        "air_gap_mode": air_gap,
        "camera": res,
    }


