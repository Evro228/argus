def get_cities_summary() -> List[Dict[str, Any]]:
    """Returns a directory of all covered cities with their camera counts and coordinates."""
    cities_map: Dict[str, Dict[str, Any]] = {}

    for cam in ALL_CAMERAS:
        city = cam["city"]
        if city not in cities_map:
            cities_map[city] = {
                "city": city,
                "city_en": cam.get("city_en", city),
                "region": cam.get("region", ""),
                "district": cam.get("district", ""),
                "country": cam["country"],
                "flag": cam["flag"],
                "lat": cam["lat"],
                "lon": cam["lon"],
                "camera_count": 0,
                "cameras": [],
            }
        cities_map[city]["camera_count"] += 1
        cities_map[city]["cameras"].append(cam["id"])

    return sorted(list(cities_map.values()), key=lambda c: (c["country"] != "RU", -c["camera_count"], c["city"]))


